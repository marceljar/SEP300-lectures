import numpy as np

a = np.array([1, 2, 3])
b = np.array([4, 5, 6])

add_result = a + b
print("Addition:", add_result)

sub_result = a - b
print("Subtraction:", sub_result)

mul_result = a * b
print("Multiplication:", mul_result)

div_result = a / b
print("Division:", div_result)

exp_result = np.exp(a)
print("Exponential:", exp_result)